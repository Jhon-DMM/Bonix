function identificarPostre(postre) {
  const identificador = `${postre.id || ''} ${postre.name || ''}`
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
  if (identificador.includes('mora')) return 'mora';
  if (identificador.includes('maracuya')) return 'maracuya';
  if (identificador.includes('milo')) return 'milo';
  return null;
}

export default function AdornosPostre({ postre, modo = 'seccion' }) {
  const clave = identificarPostre(postre);
  const imagenes = imagenesPorPostre[clave];
  const distribucionBase = modo === 'hero-frente'
    ? detallesHeroDelantePorPostre[clave]
    : distribucionPorModo[modo];
  const distribucion = modo === 'hero'
    ? [...distribucionBase, ...(detallesHeroPorPostre[clave] || [])]
    : modo === 'seccion'
      ? [...distribucionBase, ...(detallesSeccionPorPostre[clave] || [])]
    : modo === 'pagina'
      ? [...distribucionBase, ...(detallesFondoBlancoPorPostre[clave] || [])]
    : distribucionBase;
  if (!imagenes || !distribucion) return null;

  return (
    <div className={`decoraciones-postres decoraciones-postres--${modo}`} aria-hidden="true">
      {distribucion.map((adorno, indice) => (
        <img
          key={`${clave}-${modo}-${indice}`}
          className={`decoracion-postre ${adorno.centrar ? 'decoracion-postre--hojas-vaso' : ''} ${adorno.bajoTarjeta ? 'decoracion-postre--bajo-tarjeta' : ''}`}
          src={encodeURI(adorno.ruta || imagenes[adorno.imagen])}
          alt=""
          loading={modo === 'hero' ? 'eager' : 'lazy'}
          decoding="async"
          draggable="false"
          style={{
            left: adorno.izquierda,
            right: adorno.derecha,
            top: adorno.arriba,
            bottom: adorno.abajo,
            width: adorno.ancho,
            opacity: adorno.opacidad,
          transform: `${adorno.centrar ? 'translate(-50%, -50%) ' : ''}rotate(${adorno.giro}deg)`,
            '--desenfoque-postre': `${adorno.desenfoque}px`,
            '--demora-flotacion-postre': `${indice * -0.8}s`,
          }}
        />
      ))}
    </div>
  );
}
